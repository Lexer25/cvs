 * Настройки модуля eventsse: состояние эмулятора mptemu, отдаваемое в браузер
 * потоком Server-Sent Events.
 *
 * Модуль не эмулирует устройства сам: он читает файл состояния mptemu и
 * превращает его изменения в события SSE. Поэтому параметры эмулятора
 * (порт, псевдонимы комплектов, режимы имитации) остаются в config/mptemu.php.
 *
 * @package    eventsse
 */
return array(
	// Файл состояния mptemu. NULL - взять state_file из config/mptemu.php.
	// Менять нужно только для отладки: модуль рассчитан на боевой файл mptemu.
	'state_file'    => NULL,

	// Как часто SSE-сервер проверяет файл состояния, мс. Это не опрос из
	// браузера: страница соединение не переоткрывает и запросов не делает.
	'poll_ms'       => 250,

	// Комментарий-пульс в потоке, сек. Не даёт прокси и браузеру закрыть
	// «молчащее» соединение.
	'heartbeat_s'   => 10,

	// Пауза перед автопереподключением EventSource, мс.
	'retry_ms'      => 2000,

	// Через сколько секунд сервер вежливо закроет поток (событие bye), после
	// чего браузер переподключится и получит свежий snapshot. 0 - не закрывать.
	// Держим меньше max_execution_time=600 из .htaccess.
	'max_seconds'   => 300,

	// Сколько последних команд отдать в начальном снимке (история ленты).
	'replay'        => 20,

	// Сколько строк держать в ленте событий на панели.
	'feed_limit'    => 100,

	// Проверять, жив ли процесс эмулятора (tasklist по PID из состояния).
	'alive_check'   => TRUE,
	'alive_every_s' => 10,

	// Заголовок панели.
	'title'         => 'Живая панель событий',
);
